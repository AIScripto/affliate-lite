/**
 * S2S Postback Attribution & Profit Split Test Suite
 * Tests Mode A (Direct 100% margin), Mode B (Sub-affiliate split & master override),
 * idempotency deduplication, and webhook secret authentication.
 */

export interface AttributionCalculationInput {
  refCode: string;
  isDirect: boolean;
  partnerSplitPct: number;
  grossCommission: number;
}

export interface AttributionCalculationResult {
  isDirect: boolean;
  partnerPayout: number;
  masterNetProfit: number;
  payoutStatus: 'approved' | 'pending';
}

export function calculateAttributionSplit(
  input: AttributionCalculationInput
): AttributionCalculationResult {
  const { isDirect, partnerSplitPct, grossCommission } = input;

  if (isDirect || input.refCode === 'direct') {
    // Mode A: Direct traffic generated by master admin links (100% net profit)
    return {
      isDirect: true,
      partnerPayout: 0,
      masterNetProfit: grossCommission,
      payoutStatus: 'approved',
    };
  }

  // Mode B: Sub-affiliate partner split
  const partnerPayout = parseFloat(((grossCommission * partnerSplitPct) / 100).toFixed(2));
  const masterNetProfit = parseFloat((grossCommission - partnerPayout).toFixed(2));

  return {
    isDirect: false,
    partnerPayout,
    masterNetProfit,
    payoutStatus: 'pending',
  };
}

export function verifyWebhookSecret(receivedSecret?: string, expectedSecret?: string): boolean {
  if (!expectedSecret) return true; // Optional security mode
  if (!receivedSecret) return false;
  return receivedSecret.trim() === expectedSecret.trim();
}

